# ---- docs/cli.md ----

def _subcommands(parser):
    """[(name, help, subparser)] for visible subcommands, in parser order."""
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            return [(c.dest, c.help, a.choices[c.dest]) for c in a._choices_actions]
    return []


def _option_rows(parser, skip):
    rows = []
    for a in parser._actions:
        if isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)) or a.help == argparse.SUPPRESS or a.dest in skip:
            continue
        if a.option_strings:
            name = ", ".join(a.option_strings) + ("" if a.nargs == 0 else f" {a.metavar or a.dest.upper()}")
        else:
            name = a.metavar or a.dest
        help = a.help or ""
        if a.choices and not isinstance(a.choices, dict):
            help += f" (one of: {', '.join(map(str, a.choices))})"
        rows.append(f"| `{name}` | {help.replace('|', '/')} |")
    return rows


def _examples(parser):
    return [line.strip() for line in (parser.epilog or "").split("examples:", 1)[-1].splitlines() if line.startswith("  ")]


def _command(lines, path, parser, globals_):
    d = (parser.description or "").rstrip(".")
    lines += [f"## {path}", "", d[:1].upper() + d[1:] + ".", ""]
    rows = _option_rows(parser, globals_)
    if rows:
        lines += ["| Option | What it does |", "| --- | --- |", *rows, ""]
    ex = _examples(parser)
    if ex:
        lines += ["```text", *ex, "```", ""]
    for name, _, sub in _subcommands(parser):
        _command(lines, f"{path} {name}", sub, globals_)


def cli_md():
    root = cli.build_parser()
    globals_ = {a.dest for a in cli.GLOBAL._actions}
    top = _subcommands(root)
    lines = [GENERATED, "# Command reference", "",
             "Every `greenfield` command, its options and examples. Run `greenfield <command> --help` for the same text in your terminal.", "",
             "## Global options", "",
             "These work before or after the command name, for example `greenfield --json status` or `greenfield status --json`.", "",
             "| Option | What it does |", "| --- | --- |", *_option_rows(cli.GLOBAL, set()), "",
             "Exit codes: 0 success, 1 a negative result you asked about (for example a broken ledger), 2 bad input or usage, 3 environment problem, 130 interrupted.", "",
             "## Commands", "", *[f"- [`greenfield {n}`](#greenfield-{n.replace(' ', '-')}): {h}" for n, h, _ in top], ""]
    for name, _, sub in top:
        _command(lines, f"greenfield {name}", sub, globals_)
    return "\n".join(lines).rstrip("\n") + "\n"


# ---- docs/troubleshooting.md ----

def _value(node):
    """A module-level value such as gf_platform.WSL_URL, or <...> for anything only known at run time."""
    try:
        return str(eval(compile(ast.Expression(node), "<doctor>", "eval"), vars(gf_doctor)))  # names from gf_doctor's own module only
    except Exception:
        return "<...>"


def _literal(node):
    """Source text of a fix/status argument: string constants as-is, f-string values as <...>, conditionals as both branches."""
    if isinstance(node, ast.Constant):
        return [node.value] if node.value else []
    if isinstance(node, ast.JoinedStr):
        return ["".join(v.value if isinstance(v, ast.Constant) else _value(v.value) for v in node.values)]
    if isinstance(node, ast.IfExp):
        return _literal(node.body) + _literal(node.orelse)
    return []


def doctor_checks():
    """{id: {"group", "statuses", "fixes"}} read from the _r(...) calls in each function of gf_doctor.CHECKS."""
    found = {}
    for check in (*gf_doctor.CHECKS, gf_doctor._run_ctx):  # _run_ctx emits run.active for c_run
        for node in ast.walk(ast.parse(inspect.getsource(check))):
            if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "_r":
                cid = node.args[0].value
                c = found.setdefault(cid, {"group": node.args[1].value, "statuses": [], "fixes": []})
                for s in _literal(node.args[2]):
                    if s not in c["statuses"]:
                        c["statuses"].append(s)
                for f in _literal(node.args[4]) if len(node.args) > 4 else []:
                    if f not in c["fixes"]:
                        c["fixes"].append(f)
    return found


def _fix(text):
    """A fix line: a command goes in a code span, with any trailing '   (note)' left as prose."""
    cmd, sep, note = text.partition("   (")
    if not cmd.startswith(("greenfield ", "chmod ", "git ", "pipx ")):
        return f"- {text}"
    return f"- `{cmd}`" + (f" ({note}" if sep else "")


def troubleshooting_md():
    checks = doctor_checks()
    missing = sorted(set(checks) - set(MEANING))
    if missing:
        raise SystemExit(f"tools/gen_cli_docs.py: add a MEANING entry for doctor check(s): {', '.join(missing)}")
    lines = [GENERATED, "# Troubleshooting", "",
             "Start with `greenfield doctor`. It runs every check below, prints `[ ok ]`, `[warn]`, `[FAIL]` or `[info]` for each, "
             "and gives the command that fixes each problem. It changes nothing unless you pass `--fix`, which only repairs folder "
             "permissions and `.gitignore` lines, and it opens no network connections unless you pass `--network`.", "",
             "```bash", "greenfield doctor", "greenfield doctor --fix", "```", "",
             "It exits 0 when nothing failed, 1 when a check failed, and 3 on an unsupported platform. "
             "`greenfield --json doctor` prints the same results as JSON.", ""]
    for group in gf_doctor.GROUPS:
        ids = [i for i, c in checks.items() if c["group"] == group]
        if not ids:
            continue
        lines += [f"## {group}", ""]
        for cid in ids:
            c = checks[cid]
            lines += [f"### `{cid}`", "", MEANING[cid], "", "Can report: " + ", ".join(c["statuses"]) + ".", ""]
            if c["fixes"]:
                lines += ["Fix:", "", *[_fix(f) for f in c["fixes"]], ""]
    lines += ["## Still stuck", "",
              "Run `greenfield --json doctor` and open an issue at "
              "<https://github.com/aarongbaker/greenfield-business-evaluator/issues> with the output. Remove anything private first.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def generate():
    return {"docs/cli.md": cli_md(), "docs/troubleshooting.md": troubleshooting_md()}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 listing stale files")
    args = ap.parse_args(argv)
    want = generate()
    stale = [p for p, t in want.items() if not (ROOT / p).is_file() or (ROOT / p).read_bytes() != t.encode("utf-8")]
    if args.check:
        for p in stale:
            print("stale:", p, "(run python3 tools/gen_cli_docs.py)", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_bytes(want[p].encode("utf-8"))
        print("wrote", p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
